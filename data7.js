function traitInfo(name) {
  if (!name) return '';
  // 统一全角括号→半角、去除所有空白
  let n = String(name).replace(/（/g, '(').replace(/）/g, ')').replace(/\s+/g, '');
  if (TRAIT_INFO[n]) return TRAIT_INFO[n];
  // 去括号参数：威胁(3)/充能（30）→ 威胁/充能
  const base = n.replace(/\(.*?\)$/, '');
  if (TRAIT_INFO[base]) return TRAIT_INFO[base];
  // 无括号数字参数：装填1/装填2/装填 4 → 装填
  const m = n.match(/^(.+?)(\d+)$/);
  if (m && TRAIT_INFO[m[1]]) return TRAIT_INFO[m[1]];
  return TRAIT_INFO[name] || '';
}